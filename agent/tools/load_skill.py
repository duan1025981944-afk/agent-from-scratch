"""load_skill 工具：按名字把一个技能的正文交给模型。

──────────────────────────────────────────────────────────────
这个文件是什么
──────────────────────────────────────────────────────────────
渐进式加载的**第二层入口**。系统提示里常驻的是技能清单（名字 + 一句话），
模型判断某个技能有用时，调这个工具把正文取回来。

    清单（常驻）  ->  load_skill("returns-policy")  ->  正文进上下文

──────────────────────────────────────────────────────────────
这个文件不是什么
──────────────────────────────────────────────────────────────
- 它**不**读普通文件。只认技能名，不认路径——路径是 read_file 的事
- 它**不**截断正文。超长了只警告，截断仍然由 agent/payload.py 在发送前做
  （不变量 1：工具返回全文，加工只发生在发送前）
- 它**不**知道技能目录在哪、frontmatter 长什么样——那些全在 agent/skills.py

──────────────────────────────────────────────────────────────
为什么这里不做工作区越界检查
──────────────────────────────────────────────────────────────
read_file 收的是**任意路径**，合法范围无穷大，只能"先展开再判断"。

这个工具收的是**名字**，合法范围就是清单里那几个，程序早就列好了。
所以防线是**查表**：read_skill_body() 先列出所有合法技能，再按名字找，
查不到就返回 None。"../.." 永远不会出现在清单里，路径穿越自然不成立。

**范围有限用白名单，范围无限才需要边界检查。**

──────────────────────────────────────────────────────────────
一处有意的跨层 import
──────────────────────────────────────────────────────────────
本文件 import 了 agent/payload.py 的 MAX_TOOL_RESULT_CHARS —— 工具层引用
上下文层，是全项目唯一一处。只读一个常量，不调它的任何函数。

替代方案是在这里复制一个同样的数字，但**复制必然漂移**：改了一边忘了另一边，
就会出现"以为没超、其实被截了"。这和设计文档 §6 第 10 条（模板目录路径
只在 prompts.py 定义一处）是同一条理由。
"""
import warnings

from agent.payload import MAX_TOOL_RESULT_CHARS
from agent.skills import read_skill_body, skill_names
from agent.tools.base import Tool, ToolResult


class LoadSkillTool(Tool):
    """按名字读技能正文。

    谁会产生它
        agent/tools/loader.py 的 discover_tools()，启动时自动实例化。
        **不需要注册**——放进 agent/tools/ 就会被扫到。

    谁会调它
        模型，在它读完系统提示里的技能清单、决定用某个技能之后。

    类属性
        name         "load_skill"
        description  用途 + **三条反例**（反例是路由准不准的关键）
        parameters   一个必填的 name
    """

    name = "load_skill"

    description = (
        "读取一个技能的完整说明书。系统提示的「技能」一节列出了所有可用技能的名字和用途；"
        "判断某个技能对当前任务有帮助时，用它的名字调用这个工具，拿到完整步骤后照着做。\n"
        "\n"
        "不要用于以下情况：\n"
        "- 读普通文件——这个工具只认技能名、不认路径，读文件用 read_file\n"
        "- 凭印象猜技能名——名字必须来自系统提示里的技能清单\n"
        "- 重复读同一个技能——正文已经在上下文里了，除非它被省略了"
    )

    parameters = {
        "type": "object",
        "properties": {
            "name": {
                "type": "string",
                "description": "技能名，就是清单里加粗的那个词，例如 returns-policy",
            }
        },
        "required": ["name"],
    }

    async def execute(self, name: str) -> str:
        """取出正文；名字不对就返回一段告诉模型该怎么办的错误。

        返回什么
            成功：技能正文（已去掉 frontmatter，开头加了一行标题）。
            失败：ToolResult.error(...)，**里面列出当前可用的技能名**。

        为什么失败时要列出可用的名字
            这是 C 方案白赚的一笔：read_file 遇到错路径只能说"文件不存在"，
            而这个工具手里有整张表，可以直接**反向指路**。
            模型下一轮就能用对名字，不用瞎猜。

        为什么超长只警告、不截断
            截断是发送前那一道工序的事（不变量 1：工具返回全文）。
            这里截了的话，存档里留下的就是残缺正文，以后调大阈值也救不回来。

            警告走 warnings（stderr），**不进上下文** —— 这是说给你听的，
            不是说给模型听的：技能正文该拆了。
        """
        正文 = read_skill_body(name)

        if 正文 is None:
            可用 = "、".join(skill_names())
            return ToolResult.error(
                f"没有叫 {name} 的技能。"
                + (f"当前可用的技能：{可用}。" if 可用 else "当前一个技能都没有。")
                + "名字要和系统提示里技能清单上的完全一致。"
            )

        if len(正文) > MAX_TOOL_RESULT_CHARS:
            warnings.warn(
                f"技能 {name} 的正文有 {len(正文):,} 字符，超过单条上限 "
                f"{MAX_TOOL_RESULT_CHARS:,}，发给模型时尾部会被省略。"
                f"建议把细节拆进技能目录下的 references/。",
                stacklevel=2,
            )

        return 正文